@app.route('/submit-answer',methods=["POST"]) 

def submit_answer():
    global question_count
    audio_file = request.files["audio"] # accesing the audio file by key 'audio' sent from frontend

    temp_path = tempfile.NamedTemporaryFile( #this saves the audio for temparory for use
        delete=False,
        suffix='.webm',
    ).name  # name show the path of temparory saved audio

    print(f'Temp file path: {temp_path}')

    audio_file.save(temp_path) # by this the and path are saved together
    answer = speech_to_text(temp_path) # using assembly ai the audio converted in to text the saved in answer variable

    print(f"User said the following: {answer}")

    os.unlink(temp_path)  #this free up space like delete the audio that saved for temparory
    if not answer:
         answer = "Empty Text received"

    config = {'configurable':{'thread_id':thread_id}} # this will be conversation Id for noticing the conversation of hole session by AI or Agent

    agent.invoke({'messages':[{
         "role":"user",
         'content':answer
    }]},config=config)

    question_count += 1

    prompt = f'''The candidate just answered question {question_count - 1}.
   
      Look at their ACTUAL answer above. Do NOT assume or make up what they said.
      
      Now ask question {question_count} of 5:
      1. Briefly acknowledge what they ACTUALLY said (1 sentence) - quote their exact words if needed
      2. Ask your next question that builds on their REAL response (1-2 sentences)
      3. If they said "I don't know" or gave a wrong answer, acknowledge that and ask something simpler
      4. Keep the TOTAL response under 3 sentences
      
      Be conversational but CONCISE. Only reference what they true'''

    response = agent.invoke({"messages": [{"role": "user", "content": prompt}]}, config=config)

    follow_up_question = response["messages"][-1].content[0]['text']#grabing the question
    print(f"\n[follow up Question {question_count}] {follow_up_question}")
    return (
         stream_audio(follow_up_question), #sending the next question generated by AI after our response to converted the text in to audio
         {
              'Content-Type':"text/plain",
              "X-Question-Number": str(question_count) #question Number sending through headers
         } # Why not send through Body because frontend will be busy in unpacking the text or audio chunks this question Numbers will be not noticed
    )


FEEDBACK_PROMPT = """Based on our complete interview conversation, provide detailed feedback.
IMPORTANT: You MUST respond with ONLY a valid JSON object. No other text before or after.
Address the candidate directly using "you" and "your" (e.g., "You explained..." not "The candidate explained...").
Respond with ONLY this JSON structure (no markdown, no code blocks, no extra text):
{{
    "subject": "{subject}",
    "candidate_score": <1-5>,
    "feedback": "<detailed strengths with specific examples from their ACTUAL answers>",
    "areas_of_improvement": "<constructive suggestions based on gaps you noticed>"
}}
Be specific - reference ACTUAL things they said during the interview."""



@app.route('/get-feedback',methods=["POST"])

def get_feedback():
    """Generate detailed interview feedback"""
    config = {"configurable": {"thread_id": thread_id}}
    response = agent.invoke({
        "messages": [
        {
            "role": "user", 
            "content": f"{FEEDBACK_PROMPT}\n\nReview our complete {current_subject} interview conversation and provide detailed feedback."
        }
        ]
    }, config=config)
    text = response["messages"][-1].text
    print(f"\n[Feedback Generated]\n{text}\n")
    cleaned_text = text.strip()

    if cleaned_text.startswith("```json"):
        cleaned_text = cleaned_text.replace("```json", "", 1)

    elif cleaned_text.startswith("```"):
        cleaned_text = cleaned_text.replace("```", "", 1)

    if cleaned_text.endswith("```"):
        cleaned_text = cleaned_text[:-3]

    cleaned_text = cleaned_text.strip()

    feedback_json = json.loads(cleaned_text)
    

    return jsonify({"success": True, "feedback": feedback_json})
     
