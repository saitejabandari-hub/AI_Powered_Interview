#coverting text in audio with murf.ai

def stream_audio(text):

    url = "https://global.api.murf.ai/v1/speech/stream"
    headers = {
        "api-key": MURF_API_KEY,
        "Content-Type": "application/json"
    }
    data = {
    "voice_id": "en-us-natalie", #speaker name
    "text": text, # the question generated by AI
    "locale": "en-US", #language English American
    "model": "FALCON",
    "format": "MP3",
    "sampleRate": 24000,
    "channelType": "MONO"
    }

    response = requests.post(url, headers=headers, json=data, stream=True)

    if response.status_code == 200:
        # with open("audio.mp3", "wb") as f:
            for chunk in response.iter_content(chunk_size=4096):
                if chunk:
                    # f.write(chunk)
                    # Process chunks in real-time if needed
                    yield base64.b64encode(chunk).decode("utf-8")+"\n" # with base64 send each converted audio sent when it generated instead of sending everthing at one time this send at a time while generated
            print(f"Received {len(chunk)} bytes")
            print("Audio streaming completed")
    else:
        print(f"Error: {response.status_code}")


aai.settings.api_key = ASSEMBLYAI_API_KEY # assembly api accesing by assembly ai

def speech_to_text(audio_path):
     transcriber = aai.Transcriber() # some methods are provided by assembly this Transcriber() is one of it
     transcription = transcriber.transcribe(audio_path) # transcribe() is in Transcriber()

     return transcription.text if transcription.text else "" # understand it clearly





#checkpointer to save conversation in RAM

checkpointer = InMemorySaver()

#creating a Model

model = init_chat_model(
    "google_genai:gemini-3.8-flash",
    api_key = GEMINI_API_KEY
)

#creating an Agent

agent = create_agent(
    model = model,
    tools = [],
    checkpointer= checkpointer
)

#global state

question_count = 0
thread_id = "interview"
current_subject = ''

#prompt 

INTERVIEW_PROMPT = """You are Natalie, a friendly and conversational interviewer conducting a natural {subject} interview.

IMPORTANT GUIDELINES:
1. Ask exactly 5 questions total throughout the interview
2. Keep questions SHORT and CRISP (1-2 sentences maximum)
3. ALWAYS reference what the candidate ACTUALLY said in their previous answer - do NOT make up or assume their answers
4. Show genuine interest with brief acknowledgments based on their REAL responses
5. Adapt questions based on their ACTUAL responses - go deeper if they're strong, adjust if uncertain
6. Be warm and conversational but CONCISE
7. No lengthy explanations - just ask clear, direct questions

CRITICAL: Read the conversation history carefully. Only acknowledge what the candidate truly said, not what you think they might have said.

Keep it short, conversational, and adaptive!"""




@app.route('/start-interview', methods=['POST'])

def start_interview():
    data = request.json 

    global question_count, current_subject, agent, checkpointer #getting global variable if update it it will directly updated in global to

    current_subject = data.get('subject','python') #getting subject selected by user from frontend accesing through the key 'subject' and default is 'python'
    print("Question's on the subject is\n"+current_subject)

    question_count = 1

    checkpointer = InMemorySaver() #stores in RAM for that conversation untill we refresh or exit lke shortterm memory

    agent = create_agent(
        model = model,
        tools = [],
        checkpointer= checkpointer
    )

    formated_prompt = INTERVIEW_PROMPT.format(subject=current_subject) 

    config = {'configurable':{'thread_id':thread_id}}
    response = agent.invoke({
        'messages':[{'role':'system','content':formated_prompt},
                    {'role':'user','content':f"Start the interview with a warm greeting and ask the first question about {current_subject}. Keep it SHORT (1-2 sentences)."}]
    },config=config)

    question = response['messages'][-1].content[0]['text']
    print(question)

    return stream_audio(question),{'Content-Type':"text/plain"}



